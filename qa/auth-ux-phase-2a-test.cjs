'use strict';
const assert=require('assert/strict');
const fs=require('fs');
const policy=require('../netlify/functions/lib/session-policy');
const auth=fs.readFileSync(require.resolve('../netlify/functions/lib/auth.js'),'utf8');
const verify=fs.readFileSync(require.resolve('../netlify/functions/verify-pin.js'),'utf8');
const api=fs.readFileSync(require.resolve('../dashboard-p1/api.mjs'),'utf8');
const migration=fs.readFileSync(require('path').join(__dirname,'..','migrations','2026-09-11-auth-ux-phase-2a-remembered-sessions.sql'),'utf8');
assert.equal(policy.cookieMaxAge(false),8*3600);
assert.equal(policy.cookieMaxAge(true),30*24*3600);
const recent=new Date().toISOString();
assert.equal(policy.idleExpired({remembered:true,last_seen_at:recent}),false);
assert.equal(policy.idleExpired({remembered:true,last_seen_at:new Date(Date.now()-7*86400000-1).toISOString()}),true);
assert.equal(policy.idleExpired({remembered:false,last_seen_at:'2000-01-01T00:00:00Z'}),false);
assert.match(verify,/body\.remember_me===true/);
assert.match(verify,/Session duration is server-controlled/);
assert.doesNotMatch(verify,/p_expires/);
assert.match(api,/remember_me:rememberMe===true/);
for(const flag of ['HttpOnly','Secure','SameSite=Strict'])assert.match(auth+fs.readFileSync(require.resolve('../netlify/functions/lib/auth.js'),'utf8'),new RegExp(flag));
for(const field of ['remembered','credential_version','absolute_expires_at'])assert.match(migration,new RegExp(field));
assert.match(migration,/interval '8 hours'/);
assert.match(migration,/interval '30 days'/);
assert.match(migration,/practitioner_login_session/);
console.log('PASS Phase 2A server-controlled durations, idle policy, custom-expiry rejection, version fields, and cookie contract');
