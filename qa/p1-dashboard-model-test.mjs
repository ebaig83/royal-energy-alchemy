import assert from 'node:assert/strict';
import * as M from '../dashboard-p1/model.mjs';
import {sampleData} from '../dashboard-p1/fixture.mjs';
const d=sampleData(),imported=d.sessions.find(s=>M.silent(s)),online=d.sessions.find(s=>s.id==='s2');
assert.deepEqual(M.AREAS,['Today','Clients','Schedule','Communications','Finance','System']);
assert.deepEqual(M.eligibleActions({...imported,payment_status:'paid',google_meet_url:online.google_meet_url},d.now),['View']);
assert.equal(M.payment(imported)[0],'Paid noted in planner');
assert.equal(M.needsAttention(imported,d.now),false);
assert.equal(M.canJoin(online,d.now),true);
assert.equal(M.canJoin({...online,payment_status:'unpaid'},d.now),false);
assert.equal(M.canJoin({...online,status:'cancelled'},d.now),false);
assert.equal(M.canJoin({...online,google_meet_url:'javascript:alert(1)'},d.now),false);
assert.equal(M.canJoin({...online,google_meet_url:'https://meet.google.com.evil.test/a'},d.now),false);
assert.equal(M.qa(d.sessions.find(s=>s.id==='sq')),true);
assert.equal(M.forClient(d.sessions,'c3').length,1);
assert.equal(M.forClient(d.sessions,'c6').length,1);
assert.notEqual(M.forClient(d.sessions,'c3')[0].id,M.forClient(d.sessions,'c6')[0].id);
assert.equal(M.clientStats(d.clients.find(c=>c.id==='c3'),d.sessions,d.now).count,1);
const f=M.finance(d.ledger,d.sessions,'2026-09');assert.equal(f.collected,270);assert.equal(f.refunds,90);assert.equal(f.net,180);assert.equal(f.manual,70);assert.equal(f.stripe,200);assert.equal(f.balances,100);
assert.equal(M.finance(d.ledger.map(e=>({...e,entry_type:'credit'})),[], '2026-09').collected,0);
assert.equal(M.dateKey(new Date('2026-09-15T02:00:00Z')),'2026-09-14');
assert.equal(M.escapeHTML('<img onerror="x">'),'&lt;img onerror=&quot;x&quot;&gt;');
assert.equal(M.waiver({...online,waiver_completed:null})[0],'Waiver not recorded');
console.log('PASS P1 model: canonical IDs, QA filtering, silent import eligibility, finance separation, Eastern dates, XSS escaping, unknown-state handling');
