'use strict';
const assert=require('assert');
const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const dashboard=fs.readFileSync(path.join(root,'dashboard.html'),'utf8');
const app=fs.readFileSync(path.join(root,'dashboard-p1','app.mjs'),'utf8');
const api=fs.readFileSync(path.join(root,'dashboard-p1','api.mjs'),'utf8');
const request=fs.readFileSync(path.join(root,'netlify','functions','practitioner-recovery-request.js'),'utf8');
const routeIndex=dashboard.indexOf("/^#reset=([A-Za-z0-9_-]{32,128})$/");
const bodyIndex=dashboard.indexOf('<body>');
const firstLegacyScript=dashboard.indexOf('<script',bodyIndex+6);
assert(routeIndex>bodyIndex&&routeIndex<firstLegacyScript+2000,'dashboard reset gate must run at the start of the body');
assert.match(dashboard,/history\.replaceState\(null,'',location\.pathname\+location\.search\)/);
assert.match(dashboard,/document\.open\(\)[\s\S]*document\.close\(\)/);
assert.match(dashboard,/body:JSON\.stringify\(\{action:'complete',token,next:next\.value,confirm:confirm\.value\}\)/);
assert.match(dashboard,/invalid or expired/);
assert.match(app,/if\(location\.hash\.startsWith\('#reset='\)\)bindRecoveryPanel/);
assert.match(app,/function routeRecoveryFragment\(\)\{[\s\S]*location\.hash\.startsWith\('#reset='\)[\s\S]*history\.replaceState[\s\S]*renderLogin\(\)[\s\S]*bindRecoveryPanel\(app\.querySelector\('#sign-in'\)/);
assert.match(app,/hasResetRoute=forcedToken!==null\|\|location\.hash\.startsWith\('#reset='\)/);
assert.match(app,/Reset link unavailable/);
assert.match(request,/dashboard\.html#reset=/);
assert.match(app,/id=\"remember-login\"/);
assert.match(api,/remember_me:rememberMe===true/);
console.log('PASS reset fragment takes precedence over legacy dashboard bootstrap, captures token in memory, clears history, preserves authenticated-session and Remember Me contracts');
