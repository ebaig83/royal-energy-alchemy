'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const read=p=>fs.readFileSync(p,'utf8');
const sql=read('supabase/migrations/20260925020224_appointment_attribution_booking_integrity_hardening.sql');
const rpc=read('netlify/functions/lib/practitioner-appointments.js');
const sessions=read('netlify/functions/sessions.js');
const manage=read('netlify/functions/manage-appointment.js');
const notices=read('netlify/functions/lib/appointment-notices.js');
assert.match(sql,/p_actor_type text, p_actor_id text/);
const appointmentChangeSignature=sql.match(/create or replace function public\.practitioner_appointment_change\(([\s\S]*?)\) returns jsonb/);
assert.ok(appointmentChangeSignature,'appointment mutation RPC signature exists');
assert.doesNotMatch(appointmentChangeSignature[1],/p_actor\s+text/);
assert.match(sql,/revoke all on function public\.practitioner_appointment_change[\s\S]*?to service_role/);
assert.match(sql,/actor_type='client'[\s\S]*?actor_id is distinct from old\.client_id::text/);
assert.match(sql,/actor_id is null or not exists\(select 1 from public\.practitioner_users/);
assert.match(sql,/p_request uuid, p_correlation uuid/);
assert.match(sql,/action_source,p_correlation::text,p_request_path,previous_state,new_state/);
assert.match(sql,/public\.practitioner_restore_appointment/);
assert.match(sql,/public\.practitioner_update_session_with_audit/);
assert.match(sql,/public\.practitioner_create_appointment_with_audit/);
assert.match(rpc,/p_actor_type:trustedActor\.actor_type/);
assert.match(rpc,/requestId=body\.request_id/);
assert.match(rpc,/correlationId=require\('crypto'\)\.randomUUID\(\)/);
assert.match(rpc,/p_request:requestId,p_correlation:correlationId/);
assert.match(rpc,/correlation_id:persistedCorrelationId/);
assert.doesNotMatch(rpc,/typeof actor==='string'/);
assert.match(sessions,/actor_id:auth\.user\.id,actor_email:auth\.user\.email,source:'dashboard'/);
assert.match(manage,/verifyAppointmentToken/);
assert.match(manage,/actor_type:'client',actor_id:s\.client_id/);
assert.match(sessions,/practitioner_restore_appointment/);
assert.match(sessions,/practitioner_update_session_with_audit/);
assert.match(notices,/correlation_id:row\.correlation_id\|\|row\.id/);
assert.ok(notices.includes("trigger:origin+'_'+row.action"));
assert.match(read('netlify/functions/practitioner-create-session.js'),/practitioner_create_appointment_with_audit/);
console.log('appointment action actor derivation, RPC restriction, and correlation propagation checks passed');
