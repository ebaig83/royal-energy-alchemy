'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const settings = require(path.join(root, 'netlify/functions/lib/payment-request.js'));
const payment = read('netlify/functions/send-payment-link.js');
const actions = read('dashboard-p1/actions.mjs');
const create = read('netlify/functions/practitioner-create-session.js');
const reconcile = read('netlify/functions/lib/payment-reconciliation.js');
const migration = read('migrations/2026-09-10-multi-provider-payment-requests.sql');

assert.deepEqual(settings.OFF_PLATFORM, ['venmo', 'cash_app', 'paypal', 'zelle', 'other']);
assert.equal(settings.validateProvider('venmo', { venmo: { enabled: true, configured: true } }), 'venmo');
assert.throws(() => settings.validateProvider('paypal', { paypal: { enabled: false, configured: true } }), /not enabled/);
assert.throws(() => settings.validateSettingsInput({ venmo_destination: 'password=secret' }), /passwords/);
assert.match(settings._test.SENSITIVE.toString(), /token/);
assert.match(payment, /payment_requests/);
assert.match(payment, /payment_request_reference/);
assert.match(payment, /amount_due: amountDue/);
assert.match(payment, /payment_status: 'pending'/);
assert.match(payment, /payment-request:/);
assert.match(payment, /provider: 'stripe'/);
assert.match(actions, /name="request_payment_method"/);
assert.match(actions, /request_payment_method/);
assert.match(actions, /Stripe secure Checkout/);
assert.match(actions, /Selected payment method is not configured/);
assert.match(actions, /Review Summary/);
assert.match(create, /REQUEST_PAYMENT_METHODS/);
assert.match(migration, /CREATE TABLE IF NOT EXISTS public.payment_requests/);
assert.match(migration, /payment_request_reference/);
assert.match(migration, /ENABLE ROW LEVEL SECURITY/);
assert.match(reconcile, /payment_request_reference/);
assert.match(reconcile, /memo_contains_exact_payment_request_reference/);
assert.doesNotMatch(payment, /amount_paid.*=.*amountDue/);
assert.doesNotMatch(payment, /payment_status\s*:\s*['"]paid['"]/);
console.log('PASS multi-provider payment request validation, canonical amount, safe settings, reference idempotency, no paid mutation, and reconciliation priority');
